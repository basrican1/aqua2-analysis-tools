function testShapePropagationBoundaryMetrics(testCase)
canonicalOut = struct();
canonicalNorm = struct();
ctx = struct();
epochSpec = struct('mode','frames','frameRange',[1 10; 11 20], 'epochNames', {{'baseline','CNO1'}});

E = table( ...
    string(["f1_E1";"f1_E2";"f1_E3";"f1_E4"]), ...
    string(repmat("A1",4,1)), ...
    string(repmat("S1",4,1)), ...
    string(repmat("f1",4,1)), ...
    string(["f1_C1";"f1_C1";"f1_C1";"f1_C1"]), ...
    [1;2;12;13], ...
    [2;3;13;14], ...
    [100;120;110;130], ...
    [2;3;4;5], ...
    [1;2;3;4], ...
    [2;3;4;5], ...
    [3;4;5;6], ...
    [5;6;7;8], ...
    [0.4;0.5;0.6;0.7], ...
    [4;5;6;7], ...
    [10;12;11;13], ...
    [0.80;0.90;0.70;0.60], ...
    [2;7;1;9], ...
    [10;20;30;40], ...
    'VariableNames', {'event_uid','animal_id','slice_num','file_id','primary_cell_uid','t0_frame','t1_frame', ...
    'area_um2','duration_sec','rise19_sec','fall91_sec','decay_tau_sec','dff_auc_sec','dff_max2','max_prop_speed_um_per_sec', ...
    'perimeter_px','circularity','propagation_distance_px','propagation_angle_deg'});

M = table( ...
    string(["f1_E1";"f1_E2";"f1_E3";"f1_E4"]), ...
    string(repmat("f1_C1",4,1)), ...
    true(4,1), ...
    [0.05;0.20;0.15;0.40], ...
    [1;2;3;4], ...
    [0.95;0.80;0.85;0.60], ...
    'VariableNames', {'event_uid','cell_uid','is_primary_cell','frac_outside_cell','outside_cell_area_npix','cell_overlap_frac_of_event'});

canonicalOut.subset = struct('events', E, 'event_cell_map', M);
S = build_local_metrics_schema(canonicalOut, canonicalNorm, ctx, epochSpec, ...
    'propagationThresholdPx', 5, 'escapeThresholdFrac', 0.10);

verifyTrue(testCase, isfield(S.tables, 'cell_shape'));
verifyTrue(testCase, isfield(S.tables, 'cell_canonical'));
verifyTrue(testCase, isfield(S.tables, 'cell_propagation'));
verifyTrue(testCase, isfield(S.tables, 'cell_boundary'));
verifyGreaterThan(testCase, height(S.tables.cell_canonical), 0);
verifyGreaterThan(testCase, height(S.tables.cell_shape), 0);
verifyGreaterThan(testCase, height(S.tables.cell_propagation), 0);
verifyGreaterThan(testCase, height(S.tables.cell_boundary), 0);

verifyTrue(testCase, all(ismember({'mean_event_area_um2','mean_event_duration_sec','mean_event_rise19_sec', ...
    'mean_event_fall91_sec','mean_event_decay_tau_sec','mean_event_signal_auc_dff_sec', ...
    'mean_event_peak_amplitude_dff','mean_event_max_propagation_speed_um_per_sec'}, ...
    S.tables.cell_canonical.Properties.VariableNames)));
verifyTrue(testCase, all(ismember({'mean_perimeter_px','mean_circularity'}, S.tables.cell_shape.Properties.VariableNames)));
verifyTrue(testCase, all(ismember({'frac_propagative_events','mean_propagation_distance_px'}, S.tables.cell_propagation.Properties.VariableNames)));
verifyTrue(testCase, all(ismember({'mean_frac_outside_origin_cell','frac_escape_events_gt_threshold'}, S.tables.cell_boundary.Properties.VariableNames)));

reg = S.registry;
verifyTrue(testCase, any(reg.metric_id == "cell.mean_event_area_um2"));
verifyTrue(testCase, any(reg.metric_id == "cell.mean_event_duration_sec"));
verifyTrue(testCase, any(reg.metric_id == "cell.mean_event_rise19_sec"));
verifyTrue(testCase, any(reg.metric_id == "cell.mean_event_fall91_sec"));
verifyTrue(testCase, any(reg.metric_id == "cell.mean_event_decay_tau_sec"));
verifyTrue(testCase, any(reg.metric_id == "cell.mean_event_signal_auc_dff_sec"));
verifyTrue(testCase, any(reg.metric_id == "cell.mean_event_peak_amplitude_dff"));
verifyTrue(testCase, any(reg.metric_id == "cell.mean_event_max_propagation_speed_um_per_sec"));
verifyTrue(testCase, any(reg.metric_id == "cell.mean_perimeter_px"));
verifyTrue(testCase, any(reg.metric_id == "cell.mean_circularity"));
verifyTrue(testCase, any(reg.metric_id == "cell.frac_propagative_events"));
verifyTrue(testCase, any(reg.metric_id == "cell.mean_propagation_distance_px"));
verifyTrue(testCase, any(reg.metric_id == "cell.mean_frac_outside_origin_cell"));
verifyTrue(testCase, any(reg.metric_id == "cell.frac_escape_events_gt_threshold"));
end
