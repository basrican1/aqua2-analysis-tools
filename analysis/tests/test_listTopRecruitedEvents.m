function testRanksNeighborRecruitmentAndJoinsEvents(testCase)
result = struct();
result.metrics.tables.event_partition = table( ...
    string(["E1";"E1";"E1";"E2";"E2";"E3"]), ...
    string(["f1";"f1";"f1";"f1";"f1";"f2"]), ...
    string(["baseline";"baseline";"baseline";"CNO1";"CNO1";"CNO1"]), ...
    string(["C1";"C2";"C3";"C2";"C4";"C8"]), ...
    string(["C1";"C1";"C1";"C2";"C2";"C8"]), ...
    logical([true;false;false;true;false;true]), ...
    'VariableNames', {'event_uid','file_id','epoch_name','partition_cell_uid','primary_cell_uid','is_primary_cell'});

eventsTbl = table( ...
    string(["E1";"E2";"E3"]), ...
    string(["f1";"f1";"f2"]), ...
    [101;102;201], ...
    [500;700;1200], ...
    'VariableNames', {'event_uid','file_id','local_event_id','area_px2'});

T = list_top_recruited_events(result, 'TopN', 2, 'EventsTbl', eventsTbl);

testCase.verifyEqual(height(T), 2);
testCase.verifyEqual(string(T.event_uid(1)), "E1");
testCase.verifyEqual(T.n_recruited_cells(1), 2);
testCase.verifyEqual(T.local_event_id(1), 101);
testCase.verifyEqual(T.area_px2(1), 500);
testCase.verifyEqual(string(T.event_uid(2)), "E2");
testCase.verifyEqual(T.n_recruited_cells(2), 1);
end

function testSupportsEpochAndFileFilters(testCase)
result = struct();
result.metrics.tables.event_partition = table( ...
    string(["E1";"E1";"E2";"E2";"E3";"E3"]), ...
    string(["f1";"f1";"f1";"f1";"f2";"f2"]), ...
    string(["baseline";"baseline";"CNO1";"CNO1";"CNO1";"CNO1"]), ...
    string(["C1";"C2";"C2";"C4";"C3";"C5"]), ...
    string(["C1";"C1";"C2";"C2";"C3";"C3"]), ...
    logical([true;false;true;false;true;false]), ...
    'VariableNames', {'event_uid','file_id','epoch_name','partition_cell_uid','primary_cell_uid','is_primary_cell'});

T = list_top_recruited_events(result, 'EpochName', 'CNO1', 'FileID', 'f2', ...
    'EventsTbl', table());

testCase.verifyEqual(height(T), 1);
testCase.verifyEqual(string(T.event_uid), "E3");
testCase.verifyEqual(T.n_recruited_cells, 1);
end
