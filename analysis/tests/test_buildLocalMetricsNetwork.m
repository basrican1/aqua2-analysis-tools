function testSliceNetworkMetricsFromCanonical(testCase)
canonicalOut = struct();
canonicalNorm = struct();
ctx = struct();
epochSpec = struct('mode','frames','frameRange',[1 10; 11 20], 'epochNames', {{'baseline','CNO1'}});

E = table( ...
    string(["f1_E1";"f1_E2";"f1_E3";"f1_E4";"f1_E5";"f1_E6";"f1_E7";"f1_E8"]), ...
    string(repmat("A1",8,1)), ...
    string(repmat("S1",8,1)), ...
    string(repmat("f1",8,1)), ...
    string(["f1_C1";"f1_C2";"f1_C1";"f1_C2";"f1_C1";"f1_C2";"f1_C1";"f1_C2"]), ...
    [1;2;4;5;8;9;12;13], ...
    [1;2;4;5;8;9;12;13], ...
    [0.5;1.0;2.0;2.5;4.0;4.5;6.0;6.5], ...
    'VariableNames', {'event_uid','animal_id','slice_num','file_id','primary_cell_uid','t0_frame','t1_frame','t0_sec'});
C = table( ...
    string(["f1_C1";"f1_C2";"f1_C3"]), ...
    string(repmat("f1",3,1)), ...
    string(repmat("A1",3,1)), ...
    string(repmat("S1",3,1)), ...
    [1;2;3], ...
    false(3,1), NaN(3,1), [10;10;10], ...
    'VariableNames', {'cell_uid','file_id','animal_id','slice_num','local_cell_id','is_soma_like','soma_landmark_idx','cell_mask_npix'});
F = table(string("f1"), string("A1"), string("S1"), 0.5, 20, ...
    'VariableNames', {'file_id','animal_id','slice_num','frame_rate_s','n_frames'});
canonicalOut.subset = struct('events', E, 'cells', C, 'files', F);

S = build_local_metrics_schema(canonicalOut, canonicalNorm, ctx, epochSpec, ...
    'coincidenceWindowSec', 1.0, 'burstBinSec', 2.5, 'burstMinEvents', 2, 'corrBinSec', 1.0);

verifyTrue(testCase, isfield(S.tables, 'slice_network'));
verifyGreaterThan(testCase, height(S.tables.slice_network), 0);
T = S.tables.slice_network;
verifyTrue(testCase, all(ismember({'frac_active_cells','coincidence_rate','burst_fraction','mean_pairwise_cell_correlation'}, T.Properties.VariableNames)));
verifyTrue(testCase, any(S.registry.metric_id == "slice.frac_active_cells"));
verifyTrue(testCase, any(S.registry.metric_id == "slice.coincidence_rate"));
verifyTrue(testCase, any(S.registry.metric_id == "slice.burst_fraction"));
verifyTrue(testCase, any(S.registry.metric_id == "slice.mean_pairwise_cell_correlation"));

Tb = T(T.epoch_idx == 1,:);
verifyEqual(testCase, height(Tb), 1);
verifyEqual(testCase, Tb.n_total_cells, 3);
verifyEqual(testCase, Tb.n_active_cells, 2);
verifyEqual(testCase, Tb.n_events, 6);
verifyEqual(testCase, Tb.frac_active_cells, 2/3, 'AbsTol', 1e-9);
verifyEqual(testCase, Tb.coincidence_rate, 1.0, 'AbsTol', 1e-9);
verifyEqual(testCase, Tb.burst_fraction, 1.0, 'AbsTol', 1e-9);
verifyEqual(testCase, Tb.mean_pairwise_cell_correlation, -2/3, 'AbsTol', 1e-9);
end
