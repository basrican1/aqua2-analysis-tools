function testSpiderAllowlistIncludesSelectedRecruitmentAndNetworkMetrics(testCase)
result = struct();
result.metrics = struct();
result.metrics.registry = table( ...
    string(["cell.frac_events_with_neighbor_recruitment";"cell.mean_neighbor_entry_delay_sec";"cell.mean_neighbor_peak_overlap_frac_of_cell";"cell.mean_neighbor_partitions_per_event";"cell.frac_net_toward_soma_events";"slice.frac_active_cells";"slice.coincidence_rate";"slice.burst_fraction";"slice.mean_pairwise_cell_correlation"]), ...
    string([repmat("cell",5,1); repmat("slice",4,1)]), ...
    string([repmat("cell_recruitment",4,1); "cell_soma"; repmat("slice_network",4,1)]), ...
    string(["frac_events_with_neighbor_recruitment";"mean_neighbor_entry_delay_sec";"mean_neighbor_peak_overlap_frac_of_cell";"mean_neighbor_partitions_per_event";"frac_net_toward_soma_events";"frac_active_cells";"coincidence_rate";"burst_fraction";"mean_pairwise_cell_correlation"]), ...
    string(["frac_events_with_neighbor_recruitment_norm";"mean_neighbor_entry_delay_sec_norm";"mean_neighbor_peak_overlap_frac_of_cell_norm";"mean_neighbor_partitions_per_event_norm";"frac_net_toward_soma_events_norm";"frac_active_cells_norm";"coincidence_rate_norm";"burst_fraction_norm";"mean_pairwise_cell_correlation_norm"]), ...
    true(9,1), string([repmat("by_cell",5,1); repmat("by_slice",4,1)]), string(repmat("summary_line",9,1)), ...
    'VariableNames', {'metric_id','unit_level','source_table','value_column_raw','value_column_norm','supports_norm','default_comparison','default_plot'});

Tcell = table( ...
    string(repmat("f1",2,1)), ...
    [2;3], ...
    [0.2;0.4], ...
    [1;2], ...
    [0.01;0.02], ...
    [0.5;0.75], ...
    [0.3;0.6], ...
    [0;1], ...
    [0;1], ...
    [0;1], ...
    'VariableNames', {'file_id','epoch_idx','frac_events_with_neighbor_recruitment_norm','mean_neighbor_entry_delay_sec_norm', ...
    'mean_neighbor_peak_overlap_frac_of_cell_norm','mean_neighbor_partitions_per_event_norm', ...
    'frac_events_with_neighbor_recruitment','mean_neighbor_entry_delay_sec', ...
    'mean_neighbor_peak_overlap_frac_of_cell','mean_neighbor_partitions_per_event'});
Tslice = table( ...
    string(repmat("f1",2,1)), ...
    [2;3], ...
    [0.1;0.2], ...
    [0.4;0.6], ...
    [0.5;0.75], ...
    [0.25;0.5], ...
    [0;1], ...
    [0;1], ...
    [0;1], ...
    [0;1], ...
    'VariableNames', {'file_id','epoch_idx','frac_active_cells_norm','coincidence_rate_norm','burst_fraction_norm','mean_pairwise_cell_correlation_norm', ...
    'frac_active_cells','coincidence_rate','burst_fraction','mean_pairwise_cell_correlation'});
TcellSoma = table(string(repmat('f1',2,1)), [2;3], [0.2;0.4], [0;1], ...
    'VariableNames', {'file_id','epoch_idx','frac_net_toward_soma_events_norm','frac_net_toward_soma_events'});
result.metrics.tables = struct('cell_recruitment', Tcell, 'cell_soma', TcellSoma, 'slice_network', Tslice);

pol = struct('labels', {{'frequency'}}, 'valuesA', 1, 'valuesC', 1, 'uniqueFiles', {{'f1'}});
out = augment_polars_with_cell_metrics(result, pol);
labels = string(out.labels);
verifyTrue(testCase, any(labels == "cell_frac_events_with_neighbor_recruitment"));
verifyTrue(testCase, any(labels == "cell_mean_neighbor_entry_delay_sec"));
verifyTrue(testCase, any(labels == "cell_mean_neighbor_peak_overlap_frac_of_cell"));
verifyTrue(testCase, any(labels == "cell_mean_neighbor_partitions_per_event"));
verifyTrue(testCase, any(labels == "cell_frac_net_toward_soma_events"));
verifyTrue(testCase, any(labels == "slice_frac_active_cells"));
verifyTrue(testCase, any(labels == "slice_coincidence_rate"));
verifyTrue(testCase, any(labels == "slice_burst_fraction"));
verifyTrue(testCase, any(labels == "slice_mean_pairwise_cell_correlation"));
verifyFalse(testCase, any(labels == "slice_frac_primary_events_with_neighbor_recruitment"));
end
