function testPartitionMetricsFromCanonicalMap(testCase)
canonicalOut = struct();
canonicalNorm = struct();
ctx = struct();
epochSpec = struct('mode','frames','frameRange',[1 10; 11 20], 'epochNames', {{'baseline','CNO1'}});

E = table( ...
    string(["f1_E1";"f1_E2"]), ...
    string(repmat("A1",2,1)), ...
    string(repmat("S1",2,1)), ...
    string(repmat("f1",2,1)), ...
    string(["f1_C1";"f1_C1"]), ...
    [1;12], ...
    [3;14], ...
    'VariableNames', {'event_uid','animal_id','slice_num','file_id','primary_cell_uid','t0_frame','t1_frame'});

M = table( ...
    string(["f1_E1";"f1_E1";"f1_E2"]), ...
    string(["f1_C1";"f1_C2";"f1_C1"]), ...
    logical([1;0;1]), ...
    [1;2;12], ...
    [3;4;14], ...
    [3;3;3], ...
    [20;10;18], ...
    [0.50;0.25;0.40], ...
    [0.70;0.40;0.60], ...
    [0;1;0], ...
    'VariableNames', {'event_uid','cell_uid','is_primary_cell','cell_first_overlap_frame','cell_last_overlap_frame', ...
    'cell_overlap_duration_frames','cell_peak_overlap_npix','cell_peak_overlap_frac_of_cell','cell_peak_overlap_frac_of_event_frame','cell_entry_delay_from_primary_frames'});

canonicalOut.subset = struct('events', E, 'event_cell_map', M);
S = build_local_metrics_schema(canonicalOut, canonicalNorm, ctx, epochSpec);

verifyTrue(testCase, isfield(S.tables, 'event_partition'));
verifyTrue(testCase, isfield(S.tables, 'cell_recruitment'));
verifyGreaterThan(testCase, height(S.tables.event_partition), 0);
verifyGreaterThan(testCase, height(S.tables.cell_recruitment), 0);
verifyTrue(testCase, all(ismember({'frac_events_with_neighbor_recruitment','mean_neighbor_entry_delay_frames', ...
    'mean_neighbor_peak_overlap_frac_of_cell','mean_neighbor_partitions_per_event','mean_neighbor_entry_delay_sec'}, S.tables.cell_recruitment.Properties.VariableNames)));
reg = S.registry;
verifyTrue(testCase, any(reg.metric_id == "cell.frac_events_with_neighbor_recruitment"));
verifyTrue(testCase, any(reg.metric_id == "cell.mean_neighbor_entry_delay_frames"));
verifyTrue(testCase, any(reg.metric_id == "cell.mean_neighbor_peak_overlap_frac_of_cell"));
verifyTrue(testCase, any(reg.metric_id == "cell.mean_neighbor_partitions_per_event"));
verifyFalse(testCase, any(reg.metric_id == "slice.frac_primary_events_with_neighbor_recruitment"));
verifyFalse(testCase, any(reg.metric_id == "slice.mean_neighbor_entry_delay_sec"));

result = struct('metrics', struct('tables', S.tables));
Tdyn = bwaBuildDynamicSliceRecruitmentTable(result, 'transform', 'delta');
verifyGreaterThan(testCase, height(Tdyn), 0);
verifyTrue(testCase, all(ismember({'frac_primary_events_with_neighbor_recruitment','mean_neighbor_entry_delay_sec', ...
    'mean_neighbor_peak_overlap_frac_of_cell','mean_neighbor_partitions_per_event'}, Tdyn.Properties.VariableNames)));
end
