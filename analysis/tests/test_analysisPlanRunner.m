function tests = test_analysisPlanRunner
% Tests for analysis plan loader and preset runner.

tests = functiontests(localfunctions);
end

function testRunAnalysisPresetWithTemplateLikeConfig(testCase)
root = tempname;
mkdir(root);
cleanup = onCleanup(@() safeRmdir(root));
makeMiniRun(root);
makeConfigs(root);

out = runAnalysisPreset(root, 'presetName', 'genotype_compare');
testCase.verifyTrue(isfield(out, 'plan'));
testCase.verifyEqual(out.plan.presetName, 'genotype_compare');
testCase.verifyTrue(isfield(out, 'frequency'));
testCase.verifyTrue(isfield(out, 'metrics'));
testCase.verifyTrue(isfield(out, 'derived'));
end

function makeConfigs(root)
analysisCfg = struct();
analysisCfg.defaultPreset = 'genotype_compare';
analysisCfg.presets = struct();
analysisCfg.presets.drug_application = struct('epochs', struct( ...
    'mode', 'frames', 'frameRange', [1 40; 41 80], 'epochNames', {{'Base','Drug'}}));
analysisCfg.presets.genotype_compare = struct('epochs', struct( ...
    'mode', 'all', 'epochNames', {{'All'}}));
fid = fopen(fullfile(root, 'analysisConfig.json'), 'w');
fwrite(fid, jsonencode(analysisCfg, 'PrettyPrint', true), 'char');
fclose(fid);

plan = struct();
plan.defaultPreset = 'genotype_compare';
plan.presets = struct();
plan.presets.genotype_compare = struct( ...
    'epochPreset', 'genotype_compare', ...
    'subset', struct(), ...
    'metrics', {{'area_px2','duration_frames'}}, ...
    'freqGroupBy', {{'genotype'}}, ...
    'metricGroupBy', {{'genotype'}}, ...
    'areaPercentiles', [0 100], ...
    'makePlots', false, ...
    'strictQC', false);
fid = fopen(fullfile(root, 'analysisPlan.json'), 'w');
fwrite(fid, jsonencode(plan, 'PrettyPrint', true), 'char');
fclose(fid);
end

function makeMiniRun(root)
runDir = fullfile(root, 'derived', 'ingest_runs', '20260224_222222');
mkdir(runDir);

BWA_AQ2 = struct();
BWA_AQ2.fts1 = struct();
save(fullfile(root, 'BWA_AQ2.mat'), 'BWA_AQ2');

files = table( ...
    string(["f1";"f2"]), ...
    string(["a1";"a2"]), ...
    string(["WT";"KO"]), ...
    [80;80], ...
    [1;1], ...
    'VariableNames', {'file_id','animal_id','genotype','sz_t','frame_rate_s'});
cells = table( ...
    string(["f1_C1";"f2_C1"]), ...
    string(["f1";"f2"]), ...
    'VariableNames', {'cell_uid','file_id'});
events = table( ...
    string(["f1_E1";"f1_E2";"f2_E1"]), ...
    string(["f1";"f1";"f2"]), ...
    [1;2;1], ...
    [10;70;10], ...
    [12;72;12], ...
    [10;20;30], ...
    [5;6;7], ...
    'VariableNames', {'event_uid','file_id','local_event_id','t0_sec','t1_sec','area_px2','duration_frames'});
event_cell_map = table( ...
    string(["f1_E1";"f1_E2";"f2_E1"]), ...
    string(["f1_C1";"f1_C1";"f2_C1"]), ...
    true(3,1), ...
    'VariableNames', {'event_uid','cell_uid','is_primary_cell'});

save(fullfile(runDir, 'files.mat'), 'files');
save(fullfile(runDir, 'cells.mat'), 'cells');
save(fullfile(runDir, 'events.mat'), 'events');
save(fullfile(runDir, 'event_cell_map.mat'), 'event_cell_map');

fid = fopen(fullfile(root, 'derived', 'ingest_runs', 'latest_ingest.txt'), 'w');
fprintf(fid, '%s\n', runDir);
fclose(fid);
end

function safeRmdir(pathIn)
if exist(pathIn, 'dir')
    rmdir(pathIn, 's');
end
end
