function testSliceCanonicalAndNetwork(testCase)
R = makeToyResult();
out = CorrelationStats(R, 'unitLevel', 'slice', 'metricFamilies', {'shape','kinetics','activity','synchrony'}, 'epochName', 'baseline');
verifyTrue(testCase, istable(out.longTable));
verifyTrue(testCase, istable(out.wideTable));
verifyTrue(testCase, any(strcmp(out.metricIDs, 'area_um2')));
verifyTrue(testCase, any(strcmp(out.metricIDs, 'duration_sec')));
verifyTrue(testCase, any(strcmp(out.metricIDs, 'frequency')));
verifyTrue(testCase, any(strcmp(out.metricIDs, 'slice.frac_active_cells')));
verifySize(testCase, out.R, [numel(out.metricIDs) numel(out.metricIDs)]);
verifyFalse(testCase, isempty(out.pairTable));
verifyTrue(testCase, isfield(out, 'normalizationProvenance'));
verifyTrue(testCase, istable(out.normalizationProvenance.metricTable));
end

function testPrefersCalibratedCanonicalMetrics(testCase)
R = makeToyResult();
raw = R.canonical.metrics.area_um2.summaryByGroupEpoch;
raw.Properties.VariableNames{'mean_area_um2'} = 'mean_area_px2';
R.canonical.metrics.area_px2 = struct('summaryByGroupEpoch', raw);
out = CorrelationStats(R, 'unitLevel', 'slice', 'metricFamilies', {'shape'}, 'epochName', 'baseline');
verifyTrue(testCase, any(strcmp(out.metricIDs, 'area_um2')));
verifyFalse(testCase, any(strcmp(out.metricIDs, 'area_px2')));
end

