function testDefaultCellSelectionSuppressesRedundantSomaMetrics(testCase)
R = makeToyResult();
R.metrics.tables.cell_soma = table( ...
    repmat(string(["A1";"A1";"A2";"A2"]), 3, 1), ...
    repmat(string(["Slice1";"Slice2";"Slice1";"Slice2"]), 3, 1), ...
    repmat(string(["f1";"f2";"f3";"f4"]), 3, 1), ...
    repmat(string(["f1_C1";"f2_C1";"f3_C1";"f4_C1"]), 3, 1), ...
    [ones(4,1); 2*ones(4,1); 3*ones(4,1)], ...
    [repmat("baseline",4,1); repmat("CNO1",4,1); repmat("CNO2",4,1)], ...
    rand(12,1), rand(12,1), rand(12,1), rand(12,1), ...
    'VariableNames', {'animal_id','slice_num','file_id','primary_cell_uid','epoch_idx','epoch_name', ...
    'mean_soma_centroid_dist_um','mean_soma_start_dist_um','mean_soma_end_dist_um','mean_soma_net_distance_change_um'});
R.metrics.registry = [R.metrics.registry; table( ...
    string({'cell.mean_soma_centroid_dist_um';'cell.mean_soma_start_dist_um';'cell.mean_soma_end_dist_um';'cell.mean_soma_net_distance_change_um'}), ...
    string({'cell';'cell';'cell';'cell'}), ...
    string({'cell_soma';'cell_soma';'cell_soma';'cell_soma'}), ...
    string({'mean_soma_centroid_dist_um';'mean_soma_start_dist_um';'mean_soma_end_dist_um';'mean_soma_net_distance_change_um'}), ...
    repmat("", 4, 1), ...
    'VariableNames', {'metric_id','unit_level','source_table','value_column_raw','value_column_norm'})];
out = CorrelationStats(R, 'unitLevel', 'cell', 'metricFamilies', {'soma','shape','propagation','containment','activity'}, 'epochName', 'baseline');
verifyTrue(testCase, any(strcmp(out.metricIDs, 'cell.mean_soma_centroid_dist_um')));
verifyFalse(testCase, any(strcmp(out.metricIDs, 'cell.mean_soma_start_dist_um')));
verifyFalse(testCase, any(strcmp(out.metricIDs, 'cell.mean_soma_end_dist_um')));
end

