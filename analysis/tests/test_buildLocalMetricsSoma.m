function testSomaMetricsFromCanonicalMap(testCase)
canonicalOut = struct();
canonicalNorm = struct();
ctx = struct();
epochSpec = struct('mode','frames','frameRange',[1 10; 11 20], 'epochNames', {{'baseline','CNO1'}});

E = table( ...
    string(["f1_E1";"f1_E2";"f1_E3";"f1_E4"]), ...
    string(repmat("A1",4,1)), ...
    string(repmat("S1",4,1)), ...
    string(repmat("f1",4,1)), ...
    [1;2;12;13], ...
    [2;3;13;14], ...
    'VariableNames', {'event_uid','animal_id','slice_num','file_id','t0_frame','t1_frame'});

M = table( ...
    string(["f1_E1";"f1_E2";"f1_E3";"f1_E4"]), ...
    string(repmat("f1_C1",4,1)), ...
logical([1;0;1;1]), ...
    logical([1;1;1;1]), ...
    string(["toward";"away";"traverse";"undetermined"]), ...
    [0.2;-0.1;0.5;NaN], ...
    [5;6;4;3], ...
    [7;8;5;4], ...
    [3;4;2;1], ...
    'VariableNames', {'event_uid','cell_uid','is_primary_cell','soma_covered_ge50','motion_class','motion_index', ...
    'soma_centroid_dist_px','soma_start_dist_px','soma_end_dist_px'});

canonicalOut.subset = struct('events', E, 'event_cell_map', M);
S = build_local_metrics_schema(canonicalOut, canonicalNorm, ctx, epochSpec);

verifyTrue(testCase, isfield(S.tables, 'cell_soma'));
verifyGreaterThan(testCase, height(S.tables.cell_soma), 0);
verifyTrue(testCase, all(ismember({'frac_soma_events','frac_toward_events','frac_away_events','frac_traverse_events','mean_motion_index', ...
    'mean_soma_centroid_dist_px','mean_soma_start_dist_px','mean_soma_end_dist_px', ...
    'frac_net_toward_soma_events','frac_net_away_soma_events','frac_net_stationary_soma_events', ...
    'mean_soma_net_distance_change_px','mean_soma_net_distance_change_um'}, ...
    S.tables.cell_soma.Properties.VariableNames)));

reg = S.registry;
verifyTrue(testCase, any(reg.metric_id == "cell.frac_soma_events"));
verifyTrue(testCase, any(reg.metric_id == "cell.frac_toward_events"));
verifyTrue(testCase, any(reg.metric_id == "cell.frac_away_events"));
verifyTrue(testCase, any(reg.metric_id == "cell.frac_traverse_events"));
verifyTrue(testCase, any(reg.metric_id == "cell.mean_motion_index"));
verifyTrue(testCase, any(reg.metric_id == "cell.mean_soma_centroid_dist_px"));
verifyTrue(testCase, any(reg.metric_id == "cell.mean_soma_start_dist_px"));
verifyTrue(testCase, any(reg.metric_id == "cell.mean_soma_end_dist_px"));
verifyTrue(testCase, any(reg.metric_id == "cell.frac_net_toward_soma_events"));
verifyTrue(testCase, any(reg.metric_id == "cell.frac_net_away_soma_events"));
verifyTrue(testCase, any(reg.metric_id == "cell.frac_net_stationary_soma_events"));
verifyTrue(testCase, any(reg.metric_id == "cell.mean_soma_net_distance_change_um"));
end
