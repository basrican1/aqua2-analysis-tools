function P = correlationMetricPolicy(unitLevel, selectionMode)
%CORRELATIONMETRICPOLICY Correlation metric-family defaults and pruning policy.
%
%   P = correlationMetricPolicy(unitLevel, selectionMode)
%
%   unitLevel: ''event'', ''cell'', ''slice'', or ''animal''
%   selectionMode: ''broad'', ''default'', or ''strict''
%
%   Output fields:
%     P.defaultFamilies : public default families for the requested unit level
%     P.excludeIDs    : metric IDs to suppress for the requested selection mode

unitLevel = lower(char(string(unitLevel)));
selectionMode = lower(char(string(selectionMode)));
if isempty(selectionMode)
    selectionMode = 'default';
end

switch unitLevel
    case 'event'
        P.defaultFamilies = {'shape','kinetics','intensity','propagation','containment','recruitment','soma'};
    case 'cell'
        P.defaultFamilies = {'activity','shape','kinetics','intensity','propagation','containment','recruitment','soma'};
    otherwise
        P.defaultFamilies = {'activity','shape','kinetics','intensity','propagation','containment','recruitment','synchrony','soma'};
end

exclude = strings(0,1);

switch unitLevel
    case 'event'
        if any(strcmp(selectionMode, {'default','strict'}))
            exclude = [exclude; ...
                "event.cell_first_overlap_frame"; ...
                "event.cell_last_overlap_frame"; ...
                "event.cell_overlap_duration_sec"; ...
                "event.cell_peak_overlap_npix"; ...
                "event.cell_peak_overlap_frac_of_event_frame"; ...
                "event.is_recruited_partition"; ...
                "event.outside_cell_area_um2"];
        end
        if strcmp(selectionMode, 'strict')
            exclude = [exclude; ...
                "event.mean_neighbor_peak_overlap_frac_of_cell"; ...
                "event.n_neighbor_partitions"];
        end
    case 'cell'
        if any(strcmp(selectionMode, {'default','strict'}))
            exclude = [exclude; ...
                "cell.mean_soma_start_dist_um"; ...
                "cell.mean_soma_end_dist_um"; ...
                "cell.frac_escape_events_gt_threshold"];
        end
        if strcmp(selectionMode, 'strict')
            exclude = [exclude; ...
                "cell.mean_neighbor_peak_overlap_frac_of_cell"; ...
                "cell.mean_neighbor_partitions_per_event"];
        end
    otherwise
        if any(strcmp(selectionMode, {'default','strict'}))
            exclude = [exclude; ...
                "cell.mean_soma_start_dist_um"; ...
                "cell.mean_soma_end_dist_um"; ...
                "cell.frac_escape_events_gt_threshold"; ...
                "cell.frac_net_toward_soma_events"; ...
                "cell.frac_net_away_soma_events"; ...
                "cell.frac_net_stationary_soma_events"; ...
                "cell.mean_soma_net_distance_change_um"];
        end
        if strcmp(selectionMode, 'strict')
            exclude = [exclude; ...
                "cell.mean_neighbor_peak_overlap_frac_of_cell"; ...
                "cell.mean_neighbor_partitions_per_event"; ...
                "slice.mean_neighbor_peak_overlap_frac_of_cell"; ...
                "slice.mean_neighbor_partitions_per_event"];
        end
end

P.excludeIDs = unique(exclude, 'stable');
end
