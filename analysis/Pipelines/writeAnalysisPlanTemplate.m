function outPath = writeAnalysisPlanTemplate(pathIn, varargin)
% Write starter analysisPlan.json near BWA_AQ2.mat.

p = inputParser;
p.StructExpand = false;
addRequired(p, 'pathIn', @ischar);
addParameter(p, 'overwrite', false, @islogical);
parse(p, pathIn, varargin{:});

rootDir = detectRootDir(pathIn);
outPath = fullfile(rootDir, 'analysisPlan.json');
if exist(outPath, 'file') == 2 && ~p.Results.overwrite
    error('writeAnalysisPlanTemplate:Exists', 'File exists: %s (use overwrite=true)', outPath);
end

cfg = struct();
cfg.defaultPreset = 'drug_epoch_compare';
cfg.presets = struct();

cfg.presets.drug_epoch_compare = struct( ...
    'epochPreset', 'drug_application', ...
    'subset', struct(), ...
    'metrics', {{'area_px2','duration_frames','rise19_frames','fall91_frames','decay_tau_frames','dff_auc','dff_max2','max_prop_speed','perimeter_px','circularity','propagation_distance_px'}}, ...
    'freqGroupBy', {{'file_id'}}, ...
    'metricGroupBy', {{'animal_id','slice_num','file_id'}}, ...
    'dataLimitType', 'area_px2', ...
    'dataLimitPercentiles', [0 100], ...
    'dataLimitRules', {{}}, ...
    'areaPercentiles', [0 100], ...
    'makePlots', false, ...
    'strictQC', false);

cfg.presets.genotype_compare = struct( ...
    'epochPreset', 'genotype_compare', ...
    'subset', struct(), ...
    'metrics', {{'area_px2','duration_frames','dff_max2'}}, ...
    'freqGroupBy', {{'genotype'}}, ...
    'metricGroupBy', {{'genotype'}}, ...
    'dataLimitType', 'area_px2', ...
    'dataLimitPercentiles', [0 100], ...
    'dataLimitRules', {{}}, ...
    'areaPercentiles', [0 100], ...
    'makePlots', false, ...
    'strictQC', false);

cfg.presets.gender_compare = struct( ...
    'epochPreset', 'genotype_compare', ...
    'subset', struct(), ...
    'metrics', {{'area_px2','duration_frames','dff_max2'}}, ...
    'freqGroupBy', {{'gender'}}, ...
    'metricGroupBy', {{'gender'}}, ...
    'dataLimitType', 'area_px2', ...
    'dataLimitPercentiles', [0 100], ...
    'dataLimitRules', {{}}, ...
    'areaPercentiles', [0 100], ...
    'makePlots', false, ...
    'strictQC', false);

cfg.presets.treatment_compare = struct( ...
    'epochPreset', 'genotype_compare', ...
    'subset', struct(), ...
    'metrics', {{'area_px2','duration_frames','dff_max2'}}, ...
    'freqGroupBy', {{'treatment'}}, ...
    'metricGroupBy', {{'treatment'}}, ...
    'dataLimitType', 'area_px2', ...
    'dataLimitPercentiles', [0 100], ...
    'dataLimitRules', {{}}, ...
    'areaPercentiles', [0 100], ...
    'makePlots', false, ...
    'strictQC', false);

cfg.notes = ['Choose preset by runAnalysisPreset(pathIn, ''presetName'', ''...''). ' ...
    'Set one global dataset limit via dataLimitType+dataLimitPercentiles, or use dataLimitRules (legacy rule rows).'];

fid = fopen(outPath, 'w');
if fid < 0
    error('writeAnalysisPlanTemplate:OpenFail', 'Could not write: %s', outPath);
end
fwrite(fid, jsonencode(cfg, 'PrettyPrint', true), 'char');
fclose(fid);
end

function rootDir = detectRootDir(pathIn)
if exist(fullfile(pathIn, 'BWA_AQ2.mat'), 'file') == 2
    rootDir = pathIn; return
end
if exist(fullfile(pathIn, 'files.mat'), 'file') == 2 && exist(fullfile(pathIn, 'event_cell_map.mat'), 'file') == 2
    rootDir = fileparts(fileparts(fileparts(pathIn))); return
end
rootDir = pathIn;
end
