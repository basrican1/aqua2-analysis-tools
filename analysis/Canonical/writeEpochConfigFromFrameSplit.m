function outPath = writeEpochConfigFromFrameSplit(pathIn, frameRange, epochNames, varargin)
% Convenience writer for frame-based analysisConfig.json presets.
%
% Example:
%   writeEpochConfigFromFrameSplit(pathIn, ...
%       [15 266; 281 532; 533 784], ...
%       {'baseline','ExperimentalEpoch1','ExperimentalEpoch2'}, ...
%       'presetName', 'sample_epochs', ...
%       'defaultPreset', 'sample_epochs', ...
%       'overwrite', true);

p = inputParser;
p.StructExpand = false;
addRequired(p, 'pathIn', @ischar);
addRequired(p, 'frameRange', @isnumeric);
addRequired(p, 'epochNames', @(x) iscell(x) || isstring(x));
addParameter(p, 'presetName', 'drug_application', @(x) ischar(x) || isstring(x));
addParameter(p, 'defaultPreset', '', @(x) ischar(x) || isstring(x));
addParameter(p, 'overwrite', false, @islogical);
addParameter(p, 'includeTemplatePresets', false, @islogical);
addParameter(p, 'ensurePlanCompatiblePresets', true, @islogical);
addParameter(p, 'notes', '', @(x) ischar(x) || isstring(x));
parse(p, pathIn, frameRange, epochNames, varargin{:});

outPath = writeEpochConfigTemplate(pathIn, ...
    'overwrite', p.Results.overwrite, ...
    'includeTemplatePresets', p.Results.includeTemplatePresets, ...
    'ensurePlanCompatiblePresets', p.Results.ensurePlanCompatiblePresets, ...
    'presetName', char(string(p.Results.presetName)), ...
    'defaultPreset', char(string(p.Results.defaultPreset)), ...
    'mode', 'frames', ...
    'frameRange', frameRange, ...
    'epochNames', epochNames, ...
    'notes', char(string(p.Results.notes)));
end
