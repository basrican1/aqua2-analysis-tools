function T = addStorageContract(T)
n = height(T);
T.storage_status = repmat("stored", n, 1);
T.storage_level = strings(n,1);
T.metric_class = strings(n,1);
T.default_slice_summary = repmat("none", n, 1);
T.alternate_slice_summary = repmat("none", n, 1);
T.storage_notes = strings(n,1);

for i = 1:n
    nativeUnit = string(T.native_unit(i));
    displayUnit = string(T.display_unit(i));
    aggPath = string(T.aggregation_path(i));

    T.storage_level(i) = displayUnit;
    if nativeUnit == displayUnit
        T.metric_class(i) = "native";
    else
        T.metric_class(i) = "promoted";
    end

    if displayUnit == "slice"
        if nativeUnit == "slice"
            T.default_slice_summary(i) = "native_slice";
            T.storage_notes(i) = "Stored slice-native metric.";
        else
            T.storage_status(i) = "dynamic_only";
            T.storage_level(i) = "dynamic";
            T.metric_class(i) = "promoted_slice_summary";
            if nativeUnit == "cell"
                T.default_slice_summary(i) = "dynamic_cell_to_slice";
            else
                T.default_slice_summary(i) = "dynamic_event_to_slice";
            end
            T.storage_notes(i) = "Public contract treats promoted slice metrics as dynamic-only; any backing slice table is an internal cache, not a first-class stored metric.";
        end
        continue
    end

    if nativeUnit == "event" && displayUnit == "event"
        T.default_slice_summary(i) = "dynamic_event_to_cell_to_slice";
        T.alternate_slice_summary(i) = "dynamic_event_to_slice";
        T.storage_notes(i) = "Stored at event level; default slice view should be cell-promoted.";
    elseif nativeUnit == "event" && displayUnit == "cell"
        T.default_slice_summary(i) = "dynamic_cell_to_slice";
        T.alternate_slice_summary(i) = "dynamic_event_to_slice";
        T.storage_notes(i) = "Stored promoted cell metric; default slice view is mean across cell summaries.";
    elseif nativeUnit == "partition" && displayUnit == "event"
        T.default_slice_summary(i) = "dynamic_event_to_cell_to_slice";
        T.alternate_slice_summary(i) = "dynamic_event_to_slice";
        T.storage_notes(i) = "Stored event metric derived from partitions; slice views remain dynamic.";
    elseif nativeUnit == "partition" && displayUnit == "cell"
        T.default_slice_summary(i) = "dynamic_cell_to_slice";
        T.storage_notes(i) = "Stored promoted cell metric derived from partitions; slice view remains dynamic.";
    elseif nativeUnit == "cell" && displayUnit == "cell"
        T.default_slice_summary(i) = "dynamic_cell_to_slice";
        T.storage_notes(i) = "Stored cell-native metric; slice view remains dynamic.";
    else
        if contains(aggPath, "-> slice")
            T.default_slice_summary(i) = "stored_promoted_slice";
            T.storage_notes(i) = "Stored promoted slice metric.";
        else
            T.storage_notes(i) = "Stored metric; higher-level summaries are dynamic unless explicitly stored.";
        end
    end
end
end
