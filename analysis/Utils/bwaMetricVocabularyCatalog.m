function T = bwaMetricVocabularyCatalog(metricIDs)
%BWAMETRICVOCABULARYCATALOG Canonical vocabulary for metric families and lineage.

T = baseCatalog();
T = addStorageContract(T);
if nargin < 1 || isempty(metricIDs)
    return
end

metricIDs = string(metricIDs(:));
T = T(ismember(string(T.metric_id), metricIDs), :);
end

