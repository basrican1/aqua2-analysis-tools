function promotedMetricID = bwaCanonicalPromotedMetricID(metricName)
%BWACANONICALPROMOTEDMETRICID Map a canonical event-native metric to its stored cell-promoted metric.

promotedMetricID = "";
pairs = { ...
    'area_um2','cell.mean_event_area_um2'; ...
    'duration_sec','cell.mean_event_duration_sec'; ...
    'rise19_sec','cell.mean_event_rise19_sec'; ...
    'fall91_sec','cell.mean_event_fall91_sec'; ...
    'decay_tau_sec','cell.mean_event_decay_tau_sec'; ...
    'dff_auc_sec','cell.mean_event_signal_auc_dff_sec'; ...
    'dff_max2','cell.mean_event_peak_amplitude_dff'; ...
    'perimeter_um','cell.mean_perimeter_um'; ...
    'circularity','cell.mean_circularity'; ...
    'propagation_distance_um','cell.mean_propagation_distance_um'; ...
    'max_prop_speed_um_per_sec','cell.mean_event_max_propagation_speed_um_per_sec'};
for i = 1:size(pairs,1)
    if strcmp(char(string(metricName)), pairs{i,1})
        promotedMetricID = string(pairs{i,2});
        return
    end
end
end
